#!/usr/bin/env python3
"""Generate app/src/main/cpp/gfx/embedded_shaders.h from scripts/shaders/*.vert|.frag.

Requires glslangValidator on PATH (or GLSLANG_BIN env). The M1 probe keeps the
zero-vertex-buffer design: positions and colors are computed in the vertex
shader from gl_VertexIndex, so the pipeline needs no vertex input state.
"""
import hashlib
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SHADERS = os.path.join(HERE, "shaders")
OUT = os.path.join(HERE, "..", "app", "src", "main", "cpp", "gfx", "embedded_shaders.h")


def compile_glsl(path: str, stage: str) -> bytes:
    exe = os.environ.get("GLSLANG_BIN", "glslangValidator")
    cmd = [exe, "-V", "-S", stage, path, "-o", "/tmp/_mng_module.spv"]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit(f"glslangValidator failed for {path}:\n{r.stdout}\n{r.stderr}")
    with open("/tmp/_mng_module.spv", "rb") as f:
        return f.read()


def emit(name: str, blob: bytes) -> str:
    if len(blob) % 4 != 0:
        sys.exit(f"{name}: SPIR-V size {len(blob)} not a multiple of 4")
    words = [int.from_bytes(blob[i:i + 4], "little") for i in range(0, len(blob), 4)]
    lines = [f"static const uint32_t {name}[] = {{"]
    for i in range(0, len(words), 6):
        chunk = ", ".join(f"0x{w:08x}" for w in words[i:i + 6])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append(f"static const uint32_t {name}Size = {len(words)}; // words")
    return "\n".join(lines)


def main() -> None:
    vs = compile_glsl(os.path.join(SHADERS, "tri.vert"), "vert")
    fs = compile_glsl(os.path.join(SHADERS, "tri.frag"), "frag")
    header = "\n".join([
        "// GENERATED by scripts/emit_shaders.py - do not edit by hand.",
        "// M1 test triangle shaders, compiled from scripts/shaders/*.glsl with glslang.",
        "// Visible probe: small centered triangle with per-vertex RGB gradient on a",
        "// dark background; exercises interpolation and a real on-screen primitive.",
        "#pragma once",
        "",
        "#include <cstdint>",
        "",
        emit("kVertexSpirv", vs),
        "",
        emit("kFragmentSpirv", fs),
        "",
    ])
    with open(os.path.abspath(OUT), "w") as f:
        f.write(header)
    print("vertex   sha256:", hashlib.sha256(vs).hexdigest()[:16], f"({len(vs)} bytes)")
    print("fragment sha256:", hashlib.sha256(fs).hexdigest()[:16], f"({len(fs)} bytes)")
    print("wrote", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
